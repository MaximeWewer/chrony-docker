package main

import (
	"fmt"
	"os"
	"strconv"
	"strings"
)

// Config holds everything the entrypoint reads from the environment.
type Config struct {
	// Layout
	ConfigFile string
	StateDir   string
	ConfDir    string
	SourceDir  string

	// Sources
	Servers        []string
	Pools          []string
	Peers          []string
	SourceOptions  string
	RefClocks      []string
	NTSClient      bool
	NTSTrustedCert []string
	MinSources     string
	MaxDistance    string
	MaxJitter      string
	AuthSelectMode string
	LocalStratum   string
	LocalOrphan    bool
	LocalDistance  string

	// Server
	NTPPort        string
	NTSPort        string
	BindAddresses  []string
	Allow          []string
	Deny           []string
	RateLimit      string
	NTSRateLimit   string
	ClientLogLimit string
	NoClientLog    bool
	SmoothTime     string
	LeapSecList    string
	LeapSecMode    string

	// NTS server
	NTSCerts     []string
	NTSKeys      []string
	NTSKeysFile  string
	NTSNTPServer []string
	NTSRotate    string

	// Runtime
	ClockControl bool
	SeccompLevel int
	LogLevel     string
	IPMode       string
	Logs         string
	ExtraConf    string
	ExtraArgs    []string

	// Health probes
	HealthAddr      string
	HealthTimeout   float64
	HealthStratum   int
	ReadyMaxRootDis float64
}

func loadConfig() *Config {
	c := &Config{
		ConfigFile: env("CHRONY_CONF", ""),
		StateDir:   env("CHRONY_STATE_DIR", stateDir),
		ConfDir:    env("CHRONY_CONF_DIR", "/etc/chrony/conf.d"),
		SourceDir:  env("CHRONY_SOURCE_DIR", "/etc/chrony/sources.d"),

		Servers:        list("NTP_SERVERS"),
		Pools:          list("NTP_POOLS"),
		Peers:          list("NTP_PEERS"),
		SourceOptions:  env("SOURCE_OPTIONS", "iburst minpoll 6 maxpoll 10"),
		RefClocks:      list("REFCLOCKS"),
		NTSClient:      boolEnv("NTS", false),
		NTSTrustedCert: list("NTS_TRUSTED_CERTS"),
		MinSources:     env("MINSOURCES", ""),
		MaxDistance:    env("MAXDISTANCE", ""),
		MaxJitter:      env("MAXJITTER", ""),
		AuthSelectMode: env("AUTHSELECTMODE", ""),
		LocalStratum:   env("LOCAL_STRATUM", ""),
		LocalOrphan:    boolEnv("LOCAL_ORPHAN", false),
		LocalDistance:  env("LOCAL_DISTANCE", ""),

		NTPPort:        env("NTP_PORT", "123"),
		NTSPort:        env("NTS_PORT", "4460"),
		BindAddresses:  list("BIND_ADDRESS"),
		Allow:          list("ALLOW"),
		Deny:           list("DENY"),
		RateLimit:      env("RATELIMIT", ""),
		NTSRateLimit:   env("NTS_RATELIMIT", ""),
		ClientLogLimit: env("CLIENTLOGLIMIT", ""),
		NoClientLog:    boolEnv("NOCLIENTLOG", false),
		SmoothTime:     env("SMOOTHTIME", ""),
		LeapSecList:    env("LEAPSECLIST", "/usr/share/zoneinfo/leap-seconds.list"),
		LeapSecMode:    env("LEAPSECMODE", ""),

		NTSCerts:     list("NTS_SERVER_CERT"),
		NTSKeys:      list("NTS_SERVER_KEY"),
		NTSKeysFile:  env("NTS_KEYS_FILE", "/etc/chrony/nts/ntskeys"),
		NTSNTPServer: list("NTS_NTP_SERVER"),
		NTSRotate:    env("NTS_ROTATE", ""),

		ClockControl: boolEnv("CLOCK_CONTROL", false),
		SeccompLevel: intEnv("SCFILTER_LEVEL", 1),
		LogLevel:     env("LOG_LEVEL", ""),
		IPMode:       env("IP_MODE", ""),
		Logs:         env("LOGS", ""),
		ExtraConf:    env("EXTRA_CONF", ""),
		ExtraArgs:    strings.Fields(env("EXTRA_ARGS", "")),

		HealthAddr:      env("HEALTH_ADDR", ""),
		HealthTimeout:   floatEnv("HEALTH_TIMEOUT", 3),
		HealthStratum:   intEnv("HEALTH_MAX_STRATUM", 15),
		ReadyMaxRootDis: floatEnv("READY_MAX_ROOT_DISTANCE", 1),
	}

	// Default NTS server material: use it when it is actually mounted, so the
	// same image is an NTS server with a Secret and a plain NTP server without.
	if len(c.NTSCerts) == 0 && len(c.NTSKeys) == 0 {
		cert, key := "/etc/chrony/nts/tls.crt", "/etc/chrony/nts/tls.key"
		if exists(cert) && exists(key) {
			c.NTSCerts, c.NTSKeys = []string{cert}, []string{key}
		}
	}
	if !exists(c.NTSKeysFile) {
		c.NTSKeysFile = ""
	}
	if c.ConfigFile != "" && !exists(c.ConfigFile) {
		warn("CHRONY_CONF=%s does not exist, falling back to the generated configuration", c.ConfigFile)
		c.ConfigFile = ""
	}
	if c.LeapSecList != "" && c.LeapSecList != "off" && !exists(c.LeapSecList) {
		c.LeapSecList = ""
	}
	return c
}

// render builds a complete chrony.conf. Everything is explicit: nothing is
// appended after the user supplied directives except the operator's own
// EXTRA_CONF, and no "allow all" is ever added implicitly.
func render(c *Config) (string, error) {
	var b strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }

	p("# Generated by chrony-entrypoint %s - regenerated on every start.", version)
	p("# Mount a complete chrony.conf and set CHRONY_CONF to bypass this.")
	p("")

	p("# --- state (must stay on a writable volume) ---")
	p("driftfile %s/drift", c.StateDir)
	p("dumpdir %s", c.StateDir)
	p("ntsdumpdir %s", c.StateDir)
	p("pidfile %s/chronyd.pid", c.StateDir)
	// Command and monitoring access over a Unix socket only; the UDP command
	// port is disabled, which removes the remote monitoring attack surface.
	p("bindcmdaddress %s/chronyd.sock", c.StateDir)
	p("cmdport 0")
	if c.Logs != "" {
		p("logdir %s", c.StateDir)
		p("log %s", strings.Join(splitAny(c.Logs), " "))
	}
	p("")

	nSources := 0

	p("# --- time sources ---")
	for _, s := range c.Pools {
		p("pool %s", sourceLine(c, s))
		nSources++
	}
	for _, s := range c.Servers {
		p("server %s", sourceLine(c, s))
		nSources++
	}
	for _, s := range c.Peers {
		p("peer %s", sourceLine(c, s))
		nSources++
	}
	for _, r := range c.RefClocks {
		p("refclock %s", r)
		nSources++
	}
	for _, cert := range c.NTSTrustedCert {
		p("ntstrustedcerts %s", cert)
	}
	if c.LocalStratum != "" {
		line := "local stratum " + c.LocalStratum
		if c.LocalOrphan {
			line += " orphan"
		}
		if c.LocalDistance != "" {
			line += " distance " + c.LocalDistance
		}
		p("%s", line)
	}
	if exists(c.SourceDir) {
		// Sources can be added or removed by rewriting a ConfigMap and running
		// "chronyc reload sources", with no restart and no lost measurements.
		p("sourcedir %s", c.SourceDir)
	}
	p("")

	p("# --- source selection ---")
	if mode := authSelectMode(c); mode != "" {
		p("authselectmode %s", mode)
	}
	optional(p, "minsources", c.MinSources)
	optional(p, "maxdistance", c.MaxDistance)
	optional(p, "maxjitter", c.MaxJitter)
	p("")

	p("# --- NTP server ---")
	p("port %s", c.NTPPort)
	for _, a := range c.BindAddresses {
		p("bindaddress %s", a)
	}
	// Localhost is always allowed: the health and readiness probes query the
	// server through the same code path as a real client.
	p("allow 127.0.0.1")
	p("allow ::1")
	for _, d := range c.Deny {
		p("deny %s", d)
	}
	for _, a := range c.Allow {
		p("allow %s", a)
	}
	if c.RateLimit != "" && c.RateLimit != "off" {
		p("ratelimit %s", rateLimitArgs(c.RateLimit))
	}
	optional(p, "clientloglimit", c.ClientLogLimit)
	if c.NoClientLog {
		p("noclientlog")
	}
	optional(p, "smoothtime", c.SmoothTime)
	p("")

	if len(c.NTSCerts) > 0 || len(c.NTSKeys) > 0 {
		if len(c.NTSCerts) != len(c.NTSKeys) {
			return "", fmt.Errorf("NTS_SERVER_CERT has %d entries but NTS_SERVER_KEY has %d",
				len(c.NTSCerts), len(c.NTSKeys))
		}
		p("# --- NTS server ---")
		p("ntsport %s", c.NTSPort)
		for i := range c.NTSCerts {
			p("ntsservercert %s", c.NTSCerts[i])
			p("ntsserverkey %s", c.NTSKeys[i])
		}
		for _, s := range c.NTSNTPServer {
			// Tells NTS-KE clients which NTP endpoint to use; required when the
			// NTS-KE and NTP ports are reached through different addresses.
			p("ntsntpserver %s", s)
		}
		switch {
		case c.NTSRotate != "":
			p("ntsrotate %s", c.NTSRotate)
		case c.NTSKeysFile != "":
			// Shared cookie keys across replicas: never rotate them here, the
			// rotation is done by whatever manages the Secret.
			p("ntsrotate 0")
		}
		if c.NTSRateLimit != "" && c.NTSRateLimit != "off" {
			p("ntsratelimit %s", rateLimitArgs(c.NTSRateLimit))
		}
		p("")
	}

	p("# --- leap seconds ---")
	if c.LeapSecList != "" && c.LeapSecList != "off" {
		p("leapseclist %s", c.LeapSecList)
	}
	optional(p, "leapsecmode", c.LeapSecMode)
	p("")

	if exists(c.ConfDir) {
		p("# --- operator drop-ins ---")
		p("confdir %s", c.ConfDir)
		p("")
	}
	if c.ExtraConf != "" {
		p("# --- EXTRA_CONF ---")
		p("%s", strings.TrimRight(c.ExtraConf, "\n"))
		p("")
	}

	if nSources == 0 && !exists(c.SourceDir) && !exists(c.ConfDir) {
		warn("no time source configured (NTP_POOLS/NTP_SERVERS/NTP_PEERS/REFCLOCKS are all empty)")
	}
	if len(c.Allow) == 0 {
		warn("ALLOW is empty: the server answers localhost only, which is the safe default but serves no client")
	}
	if containsAll(c.Allow) && c.RateLimit == "" {
		warn("ALLOW contains \"all\": the NTP server is open to the Internet, consider RATELIMIT")
	}
	if c.ClockControl {
		warn("CLOCK_CONTROL=true: chronyd will step/slew the node clock, which needs CAP_SYS_TIME")
	}
	return b.String(), nil
}

// sourceLine appends the default options to a bare hostname. An entry that
// already carries options is used verbatim, so per-source tuning stays possible.
func sourceLine(c *Config, entry string) string {
	entry = strings.TrimSpace(entry)
	if strings.ContainsAny(entry, " \t") {
		return entry
	}
	opts := c.SourceOptions
	if c.NTSClient {
		opts = strings.TrimSpace(opts + " nts")
	}
	if opts == "" {
		return entry
	}
	return entry + " " + opts
}

// authSelectMode defaults to "require" when every source is authenticated with
// NTS, which prevents an attacker on the path from winning the selection with
// unauthenticated sources.
func authSelectMode(c *Config) string {
	if c.AuthSelectMode != "" {
		return c.AuthSelectMode
	}
	if !c.NTSClient {
		return ""
	}
	for _, s := range append(append(append([]string{}, c.Pools...), c.Servers...), c.Peers...) {
		if strings.ContainsAny(strings.TrimSpace(s), " \t") && !strings.Contains(s, "nts") {
			return "" // mixed sources: leave chrony's default
		}
	}
	if len(c.RefClocks) > 0 || c.LocalStratum != "" {
		return ""
	}
	return "require"
}

// rateLimitArgs turns the shorthand "on" into chrony's recommended parameters.
func rateLimitArgs(v string) string {
	if v == "on" || v == "true" || v == "1" {
		return "interval 3 burst 8 leak 2"
	}
	return v
}

func optional(p func(string, ...any), directive, value string) {
	if value != "" {
		p("%s %s", directive, value)
	}
}

func containsAll(v []string) bool {
	for _, s := range v {
		switch strings.TrimSpace(s) {
		case "all", "0.0.0.0/0", "::/0":
			return true
		}
	}
	return false
}

func env(key, def string) string {
	if v, ok := os.LookupEnv(key); ok {
		return strings.TrimSpace(v)
	}
	return def
}

func boolEnv(key string, def bool) bool {
	v := strings.ToLower(env(key, ""))
	switch v {
	case "":
		return def
	case "1", "true", "yes", "on", "y":
		return true
	case "0", "false", "no", "off", "n":
		return false
	}
	warn("%s=%q is not a boolean, using %v", key, v, def)
	return def
}

func intEnv(key string, def int) int {
	v := env(key, "")
	if v == "" {
		return def
	}
	n, err := strconv.Atoi(v)
	if err != nil {
		warn("%s=%q is not an integer, using %d", key, v, def)
		return def
	}
	return n
}

func floatEnv(key string, def float64) float64 {
	v := env(key, "")
	if v == "" {
		return def
	}
	f, err := strconv.ParseFloat(v, 64)
	if err != nil {
		warn("%s=%q is not a number, using %g", key, v, def)
		return def
	}
	return f
}

// list splits on commas and newlines only: a single entry may contain spaces,
// because it can carry per-source chrony options.
func list(key string) []string {
	raw := env(key, "")
	if raw == "" {
		return nil
	}
	var out []string
	for part := range strings.FieldsFuncSeq(raw, func(r rune) bool { return r == ',' || r == '\n' || r == '\r' }) {
		if p := strings.TrimSpace(part); p != "" {
			out = append(out, p)
		}
	}
	return out
}

func splitAny(raw string) []string {
	return strings.FieldsFunc(raw, func(r rune) bool {
		return r == ',' || r == '\n' || r == '\r' || r == ' ' || r == '\t'
	})
}

func exists(path string) bool {
	if path == "" {
		return false
	}
	_, err := os.Stat(path)
	return err == nil
}

func warn(format string, a ...any) {
	fmt.Fprintf(os.Stderr, "chrony-entrypoint: warning: "+format+"\n", a...)
}
